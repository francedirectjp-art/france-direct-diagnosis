def calc_trait_gap(innate_el, trait_el):
    """
    先天エレメント(星)と特性エレメント(自己認識)のギャップを検出。
    ギャップがある場合、「無意識に無理している」看破メッセージを返す。
    """
    if innate_el == trait_el:
        return {
            "has_gap": False,
            "innate_el": innate_el,
            "trait_el": trait_el,
            "message": None,
            "gap_type": "aligned",
        }

    msg = TRAIT_GAP_MESSAGES.get((innate_el, trait_el))
    if not msg:
        # フォールバック
        msg = (
            f"あなたの星は【{ELEMENT_JA[innate_el]}】ですが、"
            f"回答パターンは【{ELEMENT_JA[trait_el]}】に偏っています。"
            f"本来の自分とは違う姿を演じることで、腸と脳に負担がかかっている可能性があります。"
        )

    return {
        "has_gap": True,
        "innate_el": innate_el,
        "trait_el": trait_el,
        "innate_el_ja": ELEMENT_JA[innate_el],
        "trait_el_ja": ELEMENT_JA[trait_el],
        "message": msg,
        "gap_type": f"{innate_el}_acting_{trait_el}",
    }


