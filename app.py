def score_questionnaire(answers):
    """
    answers: [{question_id: int, answer: bool}, ...]
    特性質問(1-15)と状態質問(16-30)を分けて集計。
    30問アンケート（v3.0改訂版）対応。
    """
    q_map = {q["id"]: q for q in QUESTIONNAIRE}
    trait_scores = {"fire": 0, "earth": 0, "air": 0, "water": 0}
    state_scores = {"fire": 0, "earth": 0, "air": 0, "water": 0}

    for ans in answers:
        qid = ans.get("question_id")
        agreed = ans.get("answer", False)
        q = q_map.get(qid)
        if not q:
            continue
        if agreed:
            target = trait_scores if q["category"] == "trait" else state_scores
            target[q["element"]] += 1

    return trait_scores, state_scores


