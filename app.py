# ── 症状→臓器スコアのマッピング ──
# state質問のエレメントから、肝/腎どちらの症状かを判定
# 火(焦燥・イライラ・こわばり)・土(胃重・反芻・眠気) → 肝系症状
# 風(不眠・散漫・反芻)・水(冷え・疲労・不安) → 腎系症状
STATE_ORGAN_MAP = {
    "fire":  "liver",
    "earth": "liver",
    "air":   "kidney",
    "water": "kidney",
}

def determine_care_organ(current_el, state_scores):
    """
    ケア臓器を決定する。
    基本: 火・土→肝、風・水→腎
    補正: 症状(state_scores)が強く逆側に出ていれば逆転させる。
    
    判定ロジック:
      1. current_el の基本ケア臓器を取得
      2. state質問の回答から肝系スコアと腎系スコアを算出
      3. 逆側のスコアが基本側の1.5倍以上なら補正（逆転）
    """
    base_organ = CARE_THEME_BASE.get(current_el, "kidney")
    
    # state_scoresから肝系/腎系の症状スコアを集計
    liver_symptom = state_scores.get("fire", 0) + state_scores.get("earth", 0)
    kidney_symptom = state_scores.get("air", 0) + state_scores.get("water", 0)
    
    # 補正判定: 逆側が1.5倍以上強ければ逆転
    corrected = False
    if base_organ == "liver" and kidney_symptom > 0:
        # 本来は肝だが、腎系症状が圧倒的
        if kidney_symptom >= liver_symptom * 1.5 and kidney_symptom >= 3:
            base_organ = "kidney"
            corrected = True
    elif base_organ == "kidney" and liver_symptom > 0:
        # 本来は腎だが、肝系症状が圧倒的
        if liver_symptom >= kidney_symptom * 1.5 and liver_symptom >= 3:
            base_organ = "liver"
            corrected = True
    
    # 理由文を決定
    if corrected:
        reason = CARE_THEME_REASON_CORRECTED.get(
            (current_el, base_organ),
            CARE_THEME_REASON_BASE.get(current_el, "")
        )
    else:
        reason = CARE_THEME_REASON_BASE.get(current_el, "")
    
    return base_organ, reason, corrected

