def build_food_protocol(innate_el, current_el, care_organ, seal_rate, bugged_name):
    """
    占い的「おすすめ食材」から「身体チューニング手順書」へ進化。
    3ステップ構造:
      STEP 1: 封印フード（NG食材）— 現在エレメントが欲しがるもの
      STEP 2: 調律食材（チューニング）— 先天×ケア臓器
      STEP 3: 季節＋トランジットボーナス
    """
    # ── 警告メッセージ ──
    if seal_rate >= 60:
        warn_template = PROTOCOL_WARNING["high"]
    elif seal_rate >= 35:
        warn_template = PROTOCOL_WARNING["mid"]
    else:
        warn_template = PROTOCOL_WARNING["low"]

    bug_label = BUG_LABELS.get(current_el, "不調")
    warning = warn_template.format(
        seal_rate=int(seal_rate),
        bug_label=bug_label,
    )

    # ── STEP 1: 封印フード ──
    ng = NG_FOODS.get(current_el, NG_FOODS["earth"])

    # ── STEP 2: 調律食材 ──
    tuning_default = {"foods": ["よもぎ茶", "黒ごま", "梅干し", "生姜", "味噌"],
                      "tuning_reason": "体の調律を整える基本食材です。空っぽになった腸にインストールしてください。"}
    tuning = TUNING_FOODS.get(innate_el, {}).get(care_organ, tuning_default)

    # ── STEP 3: 季節＋トランジット ──
    season = get_season()
    seasonal = SEASONAL_TUNING.get(season, SEASONAL_TUNING["spring"])
    te = transit_element()
    bonus = TRANSIT_BONUS.get(te, TRANSIT_BONUS["water"])

    return {
        # 警告
        "warning": warning,
        "bugged_name": bugged_name,
        # STEP 1
        "ng_foods": ng["foods"],
        "ng_craving_message": ng["craving_message"],
        "ng_element": ELEMENT_JA.get(current_el, "土"),
        # STEP 2
        "tuning_foods": tuning["foods"],
        "tuning_reason": tuning["tuning_reason"],
        "tuning_element": ELEMENT_JA.get(innate_el, "火"),
        # STEP 3
        "seasonal_foods": seasonal["foods"],
        "seasonal_message": seasonal["message"],
        "transit_food": bonus["food"],
        "transit_reason": bonus["reason"],
        "transit_element": ELEMENT_JA.get(te, "水"),
    }


