def calc_seal_rate(innate_scores, state_scores):
    """
    innate_scores(先天)とstate_scores(現在)の4次元ベクトル間の
    コサイン類似度を算出し、「封印率」(0-100%)に変換する。

    コサイン類似度 = dot(A,B) / (|A| * |B|)
    封印率 = (1 - 類似度) * 100

    完全一致: 類似度=1.0 → 封印率 0%
    完全直交: 類似度=0.0 → 封印率 100%
    """
    keys = ["fire", "earth", "air", "water"]
    # innate_scoresは重み付き実数値（合計12.5前後）
    # state_scoresは0-5の整数値（合計0-20）
    # 正規化してコサイン類似度を取る
    a = [float(innate_scores.get(k, 0)) for k in keys]
    b = [float(state_scores.get(k, 0)) for k in keys]

    dot = sum(x * y for x, y in zip(a, b))
    mag_a = math.sqrt(sum(x * x for x in a))
    mag_b = math.sqrt(sum(y * y for y in b))

    if mag_a == 0 or mag_b == 0:
        return 50.0, 50.0  # データ不足時はデフォルト

    cosine_sim = dot / (mag_a * mag_b)
    cosine_sim = max(-1.0, min(1.0, cosine_sim))  # clamp

    # 封印率: 類似度が高い=ズレ小=封印率低い
    # コサイン類似度は通常0.3-1.0の範囲に収まるため、
    # 0.3-1.0を0%-100%にマッピングして感度を上げる
    raw_seal = (1.0 - cosine_sim) * 100.0

    # 感度調整: 実際のズレ幅に合わせてスケーリング
    # cosine_sim: 1.0=完全一致, ~0.5=大きいズレ
    # 封印率: 10%-85%の範囲にマッピング（0%や100%は非現実的）
    seal_rate = min(85.0, max(10.0, raw_seal * 1.5 + 8.0))
    release_rate = 100.0 - seal_rate

    return round(seal_rate, 1), round(release_rate, 1)


