def convert_to_utc(y, m, d, h, mi, tz_str="Asia/Tokyo"):
    tz = pytz.timezone(tz_str)
    local = tz.localize(datetime(y, m, d, h, mi, 0))
    return local.astimezone(pytz.utc)


def jd_from_utc(dt):
    h = dt.hour + dt.minute / 60.0 + dt.second / 3600.0
    return swe.julday(dt.year, dt.month, dt.day, h)


def calc_planets(jd):
    positions = {}
    for name, pid in PLANETS.items():
        res, _ = swe.calc_ut(jd, pid)
        lon = res[0] % 360.0
        spd = res[3]
        si = int(lon / 30.0)
        positions[name] = {
            "longitude": lon, "sign_index": si,
            "sign": ZODIAC_SIGNS[si]["name"],
            "sign_en": ZODIAC_SIGNS[si]["en"],
            "element": ZODIAC_SIGNS[si]["element"],
            "degree": lon % 30.0, "speed": spd,
            "retrograde": spd < 0,
        }
    return positions


def calc_asc(jd, lat, lon):
    try:
        _, ascmc = swe.houses(jd, lat, lon, b'P')
        alon = ascmc[0] % 360.0
        si = int(alon / 30.0)
        return {
            "longitude": alon, "sign_index": si,
            "sign": ZODIAC_SIGNS[si]["name"],
            "sign_en": ZODIAC_SIGNS[si]["en"],
            "element": ZODIAC_SIGNS[si]["element"],
            "degree": alon % 30.0,
        }
    except Exception:
        return None


def element_scores(positions, asc=None, include_asc=True):
    scores = {"fire": 0.0, "earth": 0.0, "air": 0.0, "water": 0.0}
    for pname, pdata in positions.items():
        w = PLANET_WEIGHTS.get(pname, 1.0)
        scores[pdata["element"]] += w
    if asc and include_asc:
        scores[asc["element"]] += PLANET_WEIGHTS["ASC"]
    return scores


def dominant(scores):
    return max(scores, key=scores.get)


def get_season():
    m = datetime.now().month
    if m in (3, 4, 5): return "spring"
    if m in (6, 7, 8): return "summer"
    if m in (9, 10, 11): return "autumn"
    return "winter"


def transit_element():
    now = datetime.now(pytz.utc)
    jd = jd_from_utc(now)
    pos = calc_planets(jd)
    sc = {"fire": 0, "earth": 0, "air": 0, "water": 0}
    for p in pos.values():
        sc[p["element"]] += 1
    return dominant(sc)


